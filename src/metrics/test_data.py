def regenerate_relevant_ids(movies_df):
    """
    Recompute each scenario's relevant_movie_ids from a movies dataframe.

    Deterministic genre-and-quality relevance proxy (see module docstring):
    a movie is relevant to a scenario if it matches the scenario's genre(s),
    clears its rating floor, and satisfies any language / release-year
    constraint. Results are sorted by (vote_average desc, movieId asc) so the
    output is stable. Returns {scenario_id: [movieId, ...]}.

    This is the exact procedure used to produce the hard-coded lists above;
    use it to verify or refresh them if the dataset changes.
    """
    import ast as _ast
    import pandas as _pd

    df = movies_df.copy()
    if "release_year" not in df.columns and "release_date" in df.columns:
        df["release_year"] = _pd.to_datetime(df["release_date"], errors="coerce").dt.year

    def _genres(cell):
        if isinstance(cell, list):
            return [str(g) for g in cell]
        if isinstance(cell, str) and cell.strip().startswith("["):
            try:
                return [str(g) for g in _ast.literal_eval(cell)]
            except (ValueError, SyntaxError):
                return []
        return []

    glist = df["genres_list"].fillna("[]").apply(_genres)

    out = {}
    for sid, spec in _RELEVANCE_SPECS:
        mask = _pd.Series(True, index=df.index)
        for g in (spec.get("genres") or []):
            mask &= glist.apply(lambda gs: g in gs)
        if spec.get("min_rating") is not None:
            mask &= df["vote_average"] >= spec["min_rating"]
        if spec.get("lang"):
            mask &= df["original_language"] == spec["lang"]
        if spec.get("year_start") is not None:
            mask &= df["release_year"] >= spec["year_start"]
        if spec.get("year_end") is not None:
            mask &= df["release_year"] <= spec["year_end"]
        sub = df[mask].sort_values(["vote_average", "movieId"], ascending=[False, True])
        out[sid] = [int(x) for x in sub["movieId"].tolist()]
    return out


